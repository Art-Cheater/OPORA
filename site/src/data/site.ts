export type IncidentKind = 'fault' | 'planned' | 'construction';
export type StatusId = 'accepted' | 'assigned' | 'working' | 'planned' | 'done' | 'foreign';

export interface Incident {
  id: string;
  kind: IncidentKind;
  address: string;
  what: string;
  status: string;
  statusId?: StatusId;
  /** Срок относительно сегодняшнего дня — текст считается при сборке и в браузере (formatEta), чтобы даты не устаревали. */
  etaDays?: number;
  etaTime?: string;
  etaTo?: string;
  etaPrefix?: string;
  /** Срок без привязки к дате, например «2027 год». */
  etaText?: string;
  lat: number;
  lon: number;
}

const etaDayFmt = new Intl.DateTimeFormat('ru-RU', { timeZone: 'Europe/Kirov', day: 'numeric', month: 'long' });

/** «сегодня к 21:00», «завтра, 28 сентября», «30 сентября, с 01:00 до 05:00 без света», «до 15 октября». */
export function formatEta(i: Pick<Incident, 'etaDays' | 'etaTime' | 'etaTo' | 'etaPrefix' | 'etaText'>, now = new Date()) {
  if (i.etaText) return i.etaText;
  const days = i.etaDays ?? 0;
  const day = etaDayFmt.format(new Date(now.getTime() + days * 86_400_000));
  if (i.etaTime && i.etaTo) return `${day}, с ${i.etaTime} до ${i.etaTo} без света`;
  if (i.etaPrefix) return `${i.etaPrefix} ${day}`;
  const rel = days === 0 ? 'сегодня' : days === 1 ? 'завтра' : '';
  if (i.etaTime) return `${rel || day} к ${i.etaTime}`;
  return rel ? `${rel}, ${day}` : day;
}

